def ceil_m(m): return -(-m.numerator // m.denominator)
def refund(reason, used, roundup=True, pre=True, agency=True, sick=True):
    u = ceil_m(used) if roundup else int(used)
    if sick and reason == '질병': return PAID - F(PAID, MONTHS) * u
    fee = F(PAID * 10, 100)
    if pre and reason == '개시 전': fee = F(PAID * 5, 100)
    if agency and reason == '공단': fee = 0
    return max(0, PAID - MP * u - fee)
