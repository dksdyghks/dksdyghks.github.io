def best5(pre=PRE5, lic='BC', first=None):
    bestv = None; tasks = list(T5)
    for perm in itertools.permutations(tasks):
        if any(perm.index(q) > perm.index(t) for t, ps in pre.items() for q in ps): continue
        for asg in itertools.product((0, 1), repeat=len(tasks)):
            a = dict(zip(perm, asg))
            if any(a[t] != 0 for t in lic): continue
            if first and perm.index(first[0]) > perm.index(first[1]): continue
            free = [0, 0]; fin = {}
            for t in perm:
                s = max([free[a[t]]] + [fin[q] for q in pre.get(t, '')]); fin[t] = s + T5[t]; free[a[t]] = fin[t]
            m = max(fin.values())
            if bestv is None or m < bestv: bestv = m
    return bestv
