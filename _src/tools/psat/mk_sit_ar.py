def grant(h, half=True, twin=True, adopt=True, move=True):
    older = len([k for k in h['kids'] if adopt or k[0] != 'adopt'])
    amt = 0
    for i in range(h['new']):
        order = older + i + 1
        a = 100 if order == 1 else 200 if order == 2 else 300
        if twin and h['twins']: a += 30
        amt += a
    m = h['months']
    if move and h['move']: return F(amt)
    if m >= 12: return F(amt)
    if m >= 6: return F(amt, 2) if half else F(amt)
    return F(0)
