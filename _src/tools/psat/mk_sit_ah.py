def claim(rec, safe=True, pest=True, pest_all=False, cap=True):
    amt, dmg, pst, clean = rec
    if pest: dmg = dmg - pst
    if pest_all and pst: dmg = 0
    own = 10 if (safe and clean) else 20
    if dmg <= own: return 0
    r = F(dmg - own, 100)
    if cap: r = min(r, F(60, 100))
    return amt * r
