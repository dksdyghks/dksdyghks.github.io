mi = lambda s: int(s[:2]) * 60 + int(s[3:])
def fare4(km, eight=True):
    f = 1400
    if km > 10: f += 100 * math.ceil(((min(km, 50) if eight else km) - 10) / 5)
    if eight and km > 50: f += 100 * math.ceil((km - 50) / 8)
    return f
