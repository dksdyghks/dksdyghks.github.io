def count_stv(groups, seats):
    v = sum(n for n, _ in groups); q = droop(v, seats)
    piles = {}; elected, out, log = [], set(), []
    cands = sorted({c for _, r in groups for c in r})
    def nxt(r): return next((c for c in r if c not in elected and c not in out), None)
    for n, r in groups: piles.setdefault(r[0], []).append((F(n), r))
    while len(elected) < seats:
        hope = [c for c in cands if c not in elected and c not in out]
        tal = {c: sum(w for w, _ in piles.get(c, [])) for c in hope}
        log.append(dict(tal))
        top = [c for c in hope if tal[c] >= q]
        if top:
            c = max(top, key=lambda k: tal[k]); check(sorted(tal[k] for k in top).count(tal[c]) == 1, 'tie at top')
            elected.append(c); sur = tal[c] - q; moved = []
            for w, r in piles.pop(c, []):
                t = nxt(r)
                if t and sur: moved.append((t, w * sur / tal[c])); piles.setdefault(t, []).append((w * sur / tal[c], r))
            log.append(('surplus', c, sur, moved))
        else:
            lo = min(tal.values()); low = [c for c in hope if tal[c] == lo]; check(len(low) == 1, 'tie at bottom')
            c = low[0]; out.add(c)
            for w, r in piles.pop(c, []):
                t = nxt(r)
                if t: piles.setdefault(t, []).append((w, r))
            log.append(('out', c))
    return q, elected, log
