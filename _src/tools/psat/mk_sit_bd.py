def shares(stops, riders):                               # stops: [(내릴 때 미터 요금, [내리는 사람])]
    out = {r: F(0) for r in riders}; prev = 0; on = list(riders)
    for m, off in stops:
        seg = F(m - prev, len(on))
        for r in on: out[r] += seg
        on = [r for r in on if r not in off]; prev = m
    return out
