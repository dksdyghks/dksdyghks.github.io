TT = {frozenset(k.split('-')): v for k, v in {'시청-A': 50, '시청-B': 50, '시청-C': 40, '시청-D': 25, 'A-B': 50, 'A-C': 25, 'A-D': 55, 'B-C': 45, 'B-D': 30, 'C-D': 45}.items()}   # 이동 시간(분)
def route(order, r=(1, 1, 1)):
    t, cur = 9 * 60, '시청'
    for x in order:
        t += TT[frozenset((cur, x))]
        if r[2] and x == 'D' and t < 11 * 60: t = 11 * 60
        if r[0] and x == 'B' and t > 10 * 60 + 30: return None
        t += 30; cur = x
    return t + TT[frozenset((cur, '시청'))]
def best5(r=(1, 1, 1)):
    res = sorted((v, o) for o in itertools.permutations('ABCD') if not (r[1] and o.index('C') > o.index('A')) for v in [route(o, r)] if v is not None)
    return res[0][0], [o for v, o in res if v == res[0][0]], res
