RATE = {1: F(35, 100), 2: F(1, 2), 3: F(7, 10)}
def rent1(k, cap=True, cmax=True, order=True, adult=False, pp=False):
    g, mk, kid, ad, inc = FAM[k]
    n = kid + (ad if adult else 0)
    cut = min(F(n, 10), F(3, 10)) if cmax else F(n, 10)
    if pp: v = mk * (RATE[g] - cut)
    else:
        v = mk * RATE[g]
        if not order and cap: v = min(v, inc * F(3, 10))
        v = v * (1 - cut)
    if order and cap: v = min(v, inc * F(3, 10))
    return v
