CUT = {'비영리': F(1, 2), '학교': F(3, 10)}
def fee1(k, night=True, minh=True, onecut=True, night_excl=True):
    day, s, e, who, canc = CASES[k]
    hrs = max(e - s, 2) if minh else e - s
    main = (30000 if day == '평일' else 40000) * hrs
    add = 10000 * max(0, e - max(s, 18)) if night else 0
    cuts = [CUT[w] for w in who]
    r = (max(cuts) if onecut else min(F(1), sum(cuts))) if cuts else 0
    tot = main * (1 - r) + (add if night_excl else add * (1 - r))
    if canc is not None: tot = 0 if canc >= 3 else tot / 2
    return tot
