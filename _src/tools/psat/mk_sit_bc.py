def best5(r=(1, 1, 1, 1)):
    res = []
    for a in itertools.product(range(3), repeat=5):
        m = dict(zip(CRS, a))
        if r[0] and m['A'] == m['B']: continue
        if r[1] and m['C'] == 0: continue
