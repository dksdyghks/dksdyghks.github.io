def taxi(km_x100, slow_min, night=True, round_up=False, base_only=False):
    extra_m = km_x100 * 10 - 2000
    units = (math.ceil(extra_m / 100) if round_up else extra_m // 100) if extra_m > 0 else 0
    base, add = 4800, units * 100 + slow_min * 200
    if not night: return base + add
    if base_only: return base * 12 // 10 + add
    return (base + add) * 12 // 10
