def hare(vs, s):
    q = F(sum(vs.values()), s); base = {k: int(v / q) for k, v in vs.items()}
    for k in sorted(vs, key=lambda k: vs[k] / q - base[k], reverse=True)[:s - sum(base.values())]: base[k] += 1
    return base
def divisor(vs, s, divs):
    top = sorted(((F(v, d), k) for k, v in vs.items() for d in divs), reverse=True)[:s]
    out = {k: 0 for k in vs}
    for _, k in top: out[k] += 1
    return out, top
