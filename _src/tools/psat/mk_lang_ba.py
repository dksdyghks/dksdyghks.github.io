def banzhaf(w, q):
    crit = {k: 0 for k in w}
    for r in range(1, len(w) + 1):
        for c in itertools.combinations(w, r):
            s = sum(w[k] for k in c)
            if s >= q:
                for k in c:
                    if s - w[k] < q: crit[k] += 1
    t = sum(crit.values()); return crit, {k: F(v, t) for k, v in crit.items()}

