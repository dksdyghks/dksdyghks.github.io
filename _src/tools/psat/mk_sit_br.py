def pay(k, cap=True, car_cut=True, stay_flat=True, seoul_cap=True):
    city, days, nights, car, fare = TRIP[k]
    daily = days * (12500 if (car and car_cut) else 25000)
    meal = days * 25000
    lim = 100000 if (city == '서울' and seoul_cap) else 70000
    lodge = sum((20000 if stay_flat else 0) if n is None else (min(n, lim) if cap else n) for n in nights)
    return daily + meal + lodge + (0 if car else fare)
