def pay(rec, floor=True, mcap=True, hx=True, disaster=True):
    g, wd, hd, ds = rec; w = WAGE[g]
    wh = sum(min(int(h) if floor else h, 4) for h in wd); hh = sum(min(int(h), 8) for h in hd)
    dh = sum(ds) if disaster else sum(min(int(h), 4) for h in ds)
    if not disaster: wh += dh; dh = 0
    if mcap:
        tot = wh + hh
        if tot > 40: wh = max(0, 40 - hh)
    return wh * w + hh * w * (F(3, 2) if hx else 1) + dh * w
