def shares(night=True, cross=False, rnd=True, equal=False):
    tot = {p_: F(0) for p_ in '甲乙丙丁'}; grand = 0
    for name, fare, (h, m), riders in SEG:
        f_ = F(fare)
        is_night = (h < 5) or (cross and name == 'A → B')
