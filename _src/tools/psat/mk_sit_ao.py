def refund(rec, half=True, cap=True, illegal=True, void=True):
    pct, spent, bad, voided = rec
    if void and voided: return 0
    base = spent - (bad if illegal else 0)
    if cap: base = min(base, LIMIT)
    if pct >= 15: return base
    if pct >= 10: return base / 2 if half else base
    return 0
