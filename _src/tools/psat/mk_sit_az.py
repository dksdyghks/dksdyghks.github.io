def best5(amax=True, bmin=True, afree=True, cdisc=True):
    res = []
    for a in range(NEED + 1):
        for b in range(NEED + 1 - a):
            c = NEED - a - b
            if amax and a > 40: continue
            if bmin and 0 < b < 40: continue
            cost = a * 7500 + (30000 if a and not (afree and a >= 30) else 0) + b * 9000 + (20000 if b else 0) + (c * 10500 * 9 // 10 if (cdisc and c >= 30) else c * 10500)
            res.append((cost, (a, b, c)))
    res.sort(); return res[0][0], [x for cst, x in res if cst == res[0][0]]
