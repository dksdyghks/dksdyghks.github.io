def leave_pay(wage=2500000, full_months=7, extra_days=15, cap1=1500000, cap2=1200000, floor=700000, prorate=True, first=3):
    tot = F(0)
    for m in range(1, full_months + 1):
        if m <= first: x = min(wage * F(8, 10), cap1) if cap1 else wage * F(8, 10)
        else: x = min(wage * F(5, 10), cap2) if cap2 else wage * F(5, 10)
        tot += max(x, floor)
    if extra_days:
        m = full_months + 1
        x = min(wage * F(8, 10), cap1) if m <= first else (min(wage * F(5, 10), cap2) if cap2 else wage * F(5, 10))
        x = max(x, floor)
        tot += x * F(extra_days, 30) if prorate else x
    return tot
