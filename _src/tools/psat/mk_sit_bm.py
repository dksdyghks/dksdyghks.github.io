def leave(k, cap=True, minus_first=True, attend=True, under1=True):
    yrs, rate, full = STAFF[k]
    if yrs < 1: return full if under1 else 0
    if attend and rate < 80: return full
    add = (int(yrs - 1) // 2 if minus_first else int(yrs) // 2) if yrs >= 3 else 0
    return min(15 + add, 25) if cap else 15 + add
