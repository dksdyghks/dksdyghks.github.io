def fee1(weekend=True, mult=True, disc=True, all_night=False):
    base = 50000; wk = F(12, 10) if weekend else 1
    hours = [(16, 18, False), (18, 20, True)] if not all_night else [(16, 20, True)]
    tot = 0
    for a, b, night in hours:
        if night: r = F(15, 10) * wk if mult else F(15, 10) + (wk - 1)
        else: r = wk
        tot += (b - a) * base * r
    return tot * (F(7, 10) if disc else 1)
