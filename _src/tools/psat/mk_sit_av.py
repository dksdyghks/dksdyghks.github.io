def schedules(blocks=2, minlen=2, ban=BAN, need=6):
    out = []
    for on in itertools.combinations(range(12), need):
        if any(i in ban for i in on): continue
        bl = []
        for i in on:
            if bl and bl[-1][1] == i - 1: bl[-1][1] = i
            else: bl.append([i, i])
        if blocks and len(bl) > blocks: continue
        if minlen and any(e - s_ + 1 < minlen for s_, e in bl): continue
        out.append(on)
    return out
def best5(**kw):
    cs = sorted((sum(PRICE[i] for i in on), on) for on in schedules(**kw))
    return cs[0][0], [o for c, o in cs if c == cs[0][0]]
