def river(A, C):
    S0 = (A, C, 0); D = {S0: 0}; q = deque([S0])
    while q:
        s = q.popleft(); a, c, b = s
        for da, dc in ((1, 0), (0, 1), (0, 2)):            # 어른 혼자, 아이 하나, 아이 둘
            na, nc = (a - da, c - dc) if b == 0 else (a + da, c + dc)
            if 0 <= na <= A and 0 <= nc <= C:
                t = (na, nc, 1 - b)
                if t not in D: D[t] = D[s] + 1; q.append(t)
    return D.get((0, 0, 1))
