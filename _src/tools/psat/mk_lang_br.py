REG = list(itertools.product([0, 1], repeat=4))
def worlds():
    for occ in itertools.product([0, 1], repeat=16):
        yield {r for r, o in zip(REG, occ) if o}
some = lambda W, f: any(f(*r) for r in W)
none = lambda W, f: not some(W, f)
PREM = [lambda W: none(W, lambda a, b, c, d: a and not b), lambda W: some(W, lambda a, b, c, d: b and c), lambda W: none(W, lambda a, b, c, d: c and d),
        lambda W: none(W, lambda a, b, c, d: d and not a), lambda W: some(W, lambda a, b, c, d: d)]
WS = [W for W in worlds() if all(pr(W) for pr in PREM)]
