DEBT = {'甲': (800000, 3), '乙': (2000000, 2), '丙': (1500000, 0), '丁': (5000000, 70)}     # 체납액(원), 납부기한이 지난 뒤 경과한 개월 수(0 = 기한 안에 냄)
def owed(k, cap=True, small=True, on_due_late=False, compound=False):
    amt, m = DEBT[k]
    late = m > 0 or (on_due_late and k == '丙')
    if not late: return F(amt)
    add = F(amt * 3, 100)
    months = min(m, 60) if cap else m
    base = amt + add if compound else amt
    heavy = 0 if (small and amt < 1000000) else base * F(12, 1000) * months
    return amt + add + heavy
