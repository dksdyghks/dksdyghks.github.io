# ---------------------------------------------------------------- L-BG04 네 동아리 회원 관계 (벤 영역 전수, 반드시 참)
SETS = 'SHRP'                                                # 수영, 등산, 독서, 사진
REGIONS = list(itertools.product((0, 1), repeat=4))          # 각 영역: (S, H, R, P) 소속 여부
def mdl(mask): return [r for i, r in enumerate(REGIONS) if mask >> i & 1]   # 사람이 있는 영역들
MODELS = [mdl(m) for m in range(1 << 16)]
ex = lambda M, f: any(f(*r) for r in M)                       # 그런 사람이 있다
PREM = [lambda M: not ex(M, lambda s, h, r, p: s and not h),   # 수영반 회원은 모두 등산반 회원이다
        lambda M: not ex(M, lambda s, h, r, p: h and r and p), # 등산반이면서 독서반인 사람은 아무도 사진반이 아니다
        lambda M: ex(M, lambda s, h, r, p: r and s)]          # 독서반 회원 가운데 수영반 회원이 있다
OPT4 = [lambda M: ex(M, lambda s, h, r, p: s and not p), lambda M: not ex(M, lambda s, h, r, p: r and not h), lambda M: ex(M, lambda s, h, r, p: p and h),
        lambda M: not ex(M, lambda s, h, r, p: s and p), lambda M: ex(M, lambda s, h, r, p: h and not r)]
def sat(ps): return [M for M in MODELS if all(f(M) for f in ps)]
M4 = sat(PREM)
f4 = [all(o(M) for M in M4) for o in OPT4]
