def tilings(R, C, vertical=True):
    cells = [(r, c) for r in range(R) for c in range(C)]
    def rec(filled):
        free = [x for x in cells if x not in filled]
        if not free: return 1
        r, c = free[0]; n_ = 0
        if c + 1 < C and (r, c + 1) not in filled: n_ += rec(filled | {(r, c), (r, c + 1)})
        if vertical and r + 1 < R and (r + 1, c) not in filled: n_ += rec(filled | {(r, c), (r + 1, c)})
        return n_
    return rec(frozenset())
