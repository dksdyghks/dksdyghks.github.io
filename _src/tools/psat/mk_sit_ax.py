# ---------------------------------------------------------------- S-AX05 발전기 가동 계획 (4,096가지 전수, 규칙 모두 필요)
DEM = [50, 90, 120, 70]
GEN = {'A': (50, 20, 40), 'B': (60, 40, 80), 'C': (40, 50, 40)}       # 용량(MW), 1시간 운전 비용, 켤 때 드는 비용(백만 원)
GK = 'ABC'
def plans(reserve=True, minup=True):
    for st in itertools.product(itertools.product((0, 1), repeat=3), repeat=4):
        if any(sum(GEN[GK[g]][0] for g in range(3) if st[t][g]) < DEM[t] + (10 if reserve else 0) for t in range(4)): continue
        if minup:
            col = [st[t][2] for t in range(4)]
            runs = [len(list(grp)) for key, grp in itertools.groupby(col) if key]
            if any(r < 2 for r in runs): continue
        yield st
def cost(st, start=True):
    c = sum(GEN[GK[g]][1] for t in range(4) for g in range(3) if st[t][g])
    if start: c += sum(GEN[GK[g]][2] for t in range(4) for g in range(3) if st[t][g] and (t == 0 or not st[t - 1][g]))
    return c
def best5(start=True, reserve=True, minup=True):
    cs = sorted((cost(st, start), st) for st in plans(reserve, minup))
