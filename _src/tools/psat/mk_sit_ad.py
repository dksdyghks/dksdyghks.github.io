def flip_moves(s):
    for i in range(len(s) - 1):
        t = list(s)
        for j in (i, i + 1): t[j] = '앞' if t[j] == '뒤' else '뒤'
        yield tuple(t)
def min_moves(start):
    goal = ('앞',) * len(start); seen = {start: 0}; q = deque([start])
    while q:
        s = q.popleft()
        if s == goal: return seen[s]
        for t in flip_moves(s):
            if t not in seen: seen[t] = seen[s] + 1; q.append(t)
    return None
