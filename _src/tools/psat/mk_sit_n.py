def park(minutes=205, ceil=True, best_only=True, mult=False, none=False):
    extra = minutes - 30
    units = math.ceil(extra / 10) if ceil else extra // 10
    fee = min(1000 + 500 * units, 15000)
    if none: return F(fee)
    rates = [F(50, 100), F(30, 100)]
    if best_only: return fee * (1 - max(rates))
    if mult: return fee * (1 - rates[0]) * (1 - rates[1])
    return fee * (1 - sum(rates))
