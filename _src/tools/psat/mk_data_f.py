def opts_with(ans_set, others):
    """canonical combo option list: the four distractors plus the answer, ordered by size then 가나다"""
    allx = sorted(set(others) | {ans_set}, key=lambda s: (len(s.split(', ')), s))
    check(len(allx) == 5, f'combo set {allx}')
    return allx

