def fill6(drain=True, drain_sign=-1, first=True, drain_first=False):
    a, b, d = F(1, 6), F(1, 4), F(1, 12)
    done = (a + (drain_sign * d if drain_first else 0)) if first else 0
    rate = a + b + (drain_sign * d if drain else 0)
