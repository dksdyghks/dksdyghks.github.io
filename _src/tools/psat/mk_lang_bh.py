STM = {'갑': lambda c, t: not t['을'], '을': lambda c, t: c != '갑', '병': lambda c, t: c in ('무', '을'), '정': lambda c, t: c == '을', '무': lambda c, t: c == '병'}
def worlds(stm, liars=2):
    out = []
    for c in PPL:
        for L in itertools.combinations(PPL, liars):
            t = {x: x not in L for x in PPL}
            if all(stm[x](c, t) == t[x] for x in PPL): out.append((c, set(L)))
    return out
