def bfs(start, blocked):
    d = {start: 0}; par = {start: []}; q = deque([start])
    while q:
        c = q.popleft()
        for dx, dy in JUMPS:
            n_ = (c[0] + dx, c[1] + dy)
            if 1 <= n_[0] <= 5 and 1 <= n_[1] <= 5 and n_ not in blocked:
                if n_ not in d: d[n_] = d[c] + 1; par[n_] = [c]; q.append(n_)
                elif d[n_] == d[c] + 1: par[n_].append(c)
    return d, par
