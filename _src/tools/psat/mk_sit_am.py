def levy(rec, cap=True, public=True, limit=True, farm=True):
    area, price, use, prev = rec
    per = F(price * 3, 10)
    if cap: per = min(per, 50000)
    if public and use == '공공': return 0
    if farm and use == '농업':
        dis_area = min(area, max(0, 1000 - prev)) if limit else area
        return (dis_area * per / 2 + (area - dis_area) * per) / 10000
    return area * per / 10000            # 만 원
