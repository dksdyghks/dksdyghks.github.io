def need(n):                 # 무거운 가짜 하나가 n개 후보 가운데 있을 때, 최악의 경우에도 찾는 데 필요한 최소 횟수
    if n <= 1: return 0
    return min(1 + max(need(k), need(n - 2 * k)) for k in range(1, n // 2 + 1))
def worst(coins, k_first):   # 처음에 k개 대 k개로 단 뒤 최선을 다할 때 최악의 경우 횟수
    return 1 + max(need(k_first), need(coins - 2 * k_first))
