# brute force at 1/10 scale (all bounds here are linear and scale exactly): regions of three sets
def extremes(Nn, A, B, Cc):
    res = {'AB_min': 10**9, 'ABC_min': 10**9, 'none_max': -1, 'Conly_max': -1}
    rng = range(Nn + 1)
    for abc in rng:
        for ab in range(Nn + 1 - abc):
            for ac in range(Nn + 1 - abc - ab):
                for bc in range(Nn + 1 - abc - ab - ac):
                    a_ = A - abc - ab - ac; b_ = B - abc - ab - bc; c_ = Cc - abc - ac - bc
                    if min(a_, b_, c_) < 0: continue
                    none = Nn - (abc + ab + ac + bc + a_ + b_ + c_)
                    if none < 0: continue
                    res['AB_min'] = min(res['AB_min'], ab + abc); res['ABC_min'] = min(res['ABC_min'], abc)
                    res['none_max'] = max(res['none_max'], none); res['Conly_max'] = max(res['Conly_max'], c_)
    return res
