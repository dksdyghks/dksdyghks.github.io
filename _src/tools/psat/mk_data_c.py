def combo_options(truths, options):
    """truths: {'ㄱ': bool, ...}; options: list of 'ㄱ, ㄴ' strings. Returns the answer index (exactly one must match)."""
    want = ', '.join(k for k in 'ㄱㄴㄷㄹ' if truths.get(k))
    hits = [i for i, o in enumerate(options) if o == want]
    check(len(hits) == 1, f'combo {want} appears {len(hits)} times in {options}')
    return hits[0] if hits else -1

