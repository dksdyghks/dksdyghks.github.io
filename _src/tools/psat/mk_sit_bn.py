def refund(k, cap=True, limit60=True, min15=True, low_rate=True):
    age, low, n, fare = RIDERS[k]
    if not (19 <= age <= 34) or (min15 and n < 15): return F(0)
    used = min(n, 60) if limit60 else n
    r = F(30, 100) if (low and low_rate) else F(20, 100)
    v = used * fare * r
    return min(v, 30000) if cap else v
