# ---------------------------------------------------------------- S-BN05 배낭 꾸리기 (63가지 전수, 규칙 모두 필요)
GEAR = {'A': ('물통', 1, 4), 'B': ('경량 텐트', 1, 9), 'C': ('침낭', 3, 3), 'D': ('구급상자', 1, 10), 'E': ('카메라', 4, 6), 'F': ('보조 배터리', 1, 10)}   # 무게(kg), 필요도 점수
WMAX = 10
def packs(r=(1, 1, 1)):
    res = []
    for k in range(1, 7):
        for s in itertools.combinations(GEAR, k):
            if sum(GEAR[x][1] for x in s) > WMAX: continue
            if r[0] and 'A' not in s: continue
            if r[1] and 'B' in s and 'C' not in s: continue
            if r[2] and k > 4: continue
            res.append((sum(GEAR[x][2] for x in s), s))
    m = max(v for v, _ in res); return m, [s for v, s in res if v == m], sorted(res, reverse=True)
